def classify(title):
    """Return the first rule matching a problem title, or None."""
    for rule in RULES:
        if rule["re"].search(title):
            return rule
    return None


def with_recall(rule, title):
    """The rule's 'what to do', plus a recall reminder when the title says recall."""
    todo = rule["w"]
    if re.search(r"recall|buyback", title, re.I) and "nhtsa.gov" not in todo:
        todo = todo + " " + RECALL_NOTE
    return todo
