"""
Car Doctor - plain-English signs and fixes for vehicle problem titles.

data/us_vehicles.json lists each vehicle generation's commonly reported
problems as short titles ("CVT judder", "10R80 harsh shifting"). These rules
turn every title into:
  - kind:  a shared id, so the same problem on 50 vehicles shares one text
  - cause: a key from app/causes.json (or None), for the diagnosis boost
  - s:     signs, in everyday words
  - w:     what to do

The FIRST rule whose pattern matches the title wins, so specific rules come
before general ones. build_vehicles.py fails if a title matches nothing.
"""

